/**
 * Systematic Authorization Matrix for ESTAFET (Phase R8 Quality Gate, Item 5).
 *
 * Documents every page route, API route handler, user Server Action, and admin Server Action,
 * along with who may call it, who must be rejected, the enforcement layer, expected denial behavior,
 * and any IDOR object parameters that must be bound to the authenticated caller.
 */

export type Role =
  | "guest"
  | "authenticated"
  | "verified"
  | "unverified"
  | "suspended"
  | "owner"
  | "co_owner"
  | "invited_co_owner"
  | "holder"
  | "revoked_holder"
  | "requester"
  | "stranger"
  | "admin";

export interface AuthzEntry {
  id: string;
  kind: "page" | "api" | "action" | "admin_action";
  target: string;
  sourceFile: string;
  allowedRoles: Role[];
  deniedRoles: Role[];
  enforcementLayer: ("proxy" | "rls" | "rpc" | "route" | "action")[];
  expectedDenial: string;
  idorParams?: string[];
}

