// Rebuilds supabase/setup-all.sql from the migrations and the seed, in order. Run: node scripts/build-setup-all.mjs
// Source of truth stays supabase/migrations/*.sql and supabase/seed.sql. This file is only a convenience for the SQL Editor.
import { readFileSync, writeFileSync } from "node:fs";

const read = (p) => readFileSync(p, "utf8").replace(/\r\n/g, "\n").trimEnd();

const parts = [
  ["PART 1: SCHEMA", "supabase/migrations/20261119000001_schema.sql"],
  ["PART 2: ADMIN AREA", "supabase/migrations/20261120000001_admin.sql"],
  ["PART 3: RELEASE R1 (enum values)", "supabase/migrations/20261121000001_r1_enum_additions.sql"],
  ["PART 4: RELEASE R1 (access model)", "supabase/migrations/20261121000002_r1_access_model.sql"],
];
const seed = ["PART 5: DEMO SEED (optional)", "supabase/seed.sql"];

let out = `-- ESTAFET: full database setup (schema + admin area + release R1 + demo seed) in ONE file.
-- For the Supabase SQL Editor (cloud) or: psql "$DATABASE_URL" -f supabase/setup-all.sql
-- Source of truth: supabase/migrations/*.sql then supabase/seed.sql. Run on an EMPTY database.
-- Seed is optional and all demo rows are is_demo = true. Skip PART 5 for a real deployment.
-- Generated by scripts/build-setup-all.mjs. Do not edit by hand.
`;
for (const [title, file] of [...parts, seed]) {
  out += `\n-- ===================== ${title} =====================\n${read(file)}\n`;
}
writeFileSync("supabase/setup-all.sql", out, "utf8");
console.log(`supabase/setup-all.sql rebuilt (${out.split("\n").length} lines)`);
